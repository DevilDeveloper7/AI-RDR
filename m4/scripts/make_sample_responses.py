"""Generate data/sample_responses.json for M6 by RUNNING M4's real enricher
with offline mock providers (no network, no keys).

The verdict logic, caching and response shape are the real code. The
indicators and provider answers are MOCK data, labelled as such.

    .venv/bin/python scripts/make_sample_responses.py
"""
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from m4_threat_intel.cache import Cache  # noqa: E402
from m4_threat_intel.enricher import Enricher  # noqa: E402
from m4_threat_intel.providers.base import Provider  # noqa: E402
from m4_threat_intel.providers.mock import load_mock_providers  # noqa: E402


class AlwaysFails(Provider):
    supported_types = frozenset({"hash", "ip", "domain"})

    def __init__(self, name, context_only=False):
        self.name, self.context_only = name, context_only

    def _lookup(self, ioc_type, value):
        return self.error("timeout (gave up after 4 attempts)")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(root)
    tmp = tempfile.TemporaryDirectory()
    cache = Cache(os.path.join(tmp.name, "c.sqlite3"))
    primary, secondary = load_mock_providers("data/mock_iocs.json")
    mock = Enricher(primary, secondary, cache=cache)
    failing = Enricher(AlwaysFails("abusech"), AlwaysFails("otx", context_only=True))

    samples = {
        "_note": "Generated by scripts/make_sample_responses.py from M4's real code with "
                 "MOCK providers. Indicators and provider answers are fake (tag MOCK-DATA).",
        "malicious": mock.enrich("A-1001", "domain", "mock-c2.example"),
        "suspicious_otx_only": mock.enrich("A-1002", "domain", "mock-noisy.example"),
        "unknown_not_found": mock.enrich("A-1003", "domain", "not-in-any-feed.example"),
        "unknown_lookup_failed": failing.enrich("A-1004", "domain", "x.example"),
        "cached": mock.enrich("A-1005", "domain", "mock-c2.example"),
    }
    cache.close()
    tmp.cleanup()
    with open("data/sample_responses.json", "w", encoding="utf-8") as fh:
        json.dump(samples, fh, indent=2)
    for name, resp in samples.items():
        if not name.startswith("_"):
            print(f"{name:24} verdict={resp['verdict']:10} score={resp['score']:3} "
                  f"cached={resp['cached']} error={resp['error']}")


if __name__ == "__main__":
    main()
